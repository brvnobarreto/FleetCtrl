            onSurfaceVariant = PurplePalette.OnSurfaceVariantDark,
            onBackground = PurplePalette.OnBackgroundDark
        )
        ColorPaletteType.BLUE -> ColorPalette(
            type = colorPalette.type,
            name = colorPalette.name,
            primary = BluePalette.PrimaryDark,
            primaryVariant = BluePalette.PrimaryVariantDark,
            secondary = BluePalette.SecondaryDark,
            secondaryVariant = BluePalette.SecondaryVariantDark,
            tertiary = BluePalette.TertiaryDark,
            tertiaryVariant = BluePalette.TertiaryVariantDark,
            surface = BluePalette.SurfaceDark,
            surfaceVariant = BluePalette.SurfaceVariantDark,
